/**
 * generate-countries.mjs — ISO 3166 and 4217, as a module the app can read.
 *
 * Export paperwork needs a country's two-letter code and the currency it
 * trades in, and both are fixed facts that nobody at the nursery should be
 * typing per invoice. There are 249 of them and they change about once a
 * decade, so they belong in the bundle rather than in Dataverse: no table to
 * keep in step, no read to fail.
 *
 * Source: https://github.com/datasets/country-codes (public domain), which
 * carries ISO 3166-1 and ISO 4217 in one file.
 *
 * Run: node scripts/dataverse/generate-countries.mjs
 */
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
const OUT = join(ROOT, 'src', 'services', 'countries.generated.ts')
/** The import scripts need the same list, and cannot import a .ts module. */
const OUT_MJS = join(ROOT, 'scripts', 'lib', 'countries.mjs')
const SOURCE = 'https://raw.githubusercontent.com/datasets/country-codes/main/data/country-codes.csv'

/** The sources quote fields and embed commas; a split(',') loses half of them. */
function parseCsv(text) {
  const rows = []
  let row = [], field = '', quoted = false
  for (let i = 0; i < text.length; i++) {
    const c = text[i]
    if (quoted) {
      if (c === '"') { if (text[i + 1] === '"') { field += '"'; i++ } else quoted = false }
      else field += c
    } else if (c === '"') quoted = true
    else if (c === ',') { row.push(field); field = '' }
    else if (c === '\n') { row.push(field); rows.push(row); row = []; field = '' }
    else if (c !== '\r') field += c
  }
  if (field || row.length) { row.push(field); rows.push(row) }
  const head = rows.shift().map((h) => h.replace(/^﻿/, '').trim())
  return rows.filter((r) => r.length > 1).map((r) => Object.fromEntries(head.map((h, i) => [h, (r[i] ?? '').trim()])))
}

const res = await fetch(SOURCE)
if (!res.ok) throw new Error(`${SOURCE} answered ${res.status}`)

const countries = parseCsv(await res.text())
  .filter((c) => c['ISO3166-1-Alpha-2'] && (c['CLDR display name'] || c['official_name_en']))
  .map((c) => ({
    code: c['ISO3166-1-Alpha-2'],
    code3: c['ISO3166-1-Alpha-3'],
    // M49, which is what UN trade data speaks: its rows name partners as 340,
    // not HN.
    numeric: Number(c['ISO3166-1-numeric']) || 0,
    // CLDR is what a person would say — except where it abbreviates to the
    // point of uselessness on paperwork: the United States is listed as "US".
    name: (c['CLDR display name'] || '').length > 3
      ? c['CLDR display name']
      : (c['official_name_en'] || c['CLDR display name']),
    // Every other spelling the data around here uses. The port lists say
    // "United States", the ISO file says "United States of America", and a
    // country is not two countries because two sources disagree.
    aliases: [...new Set([c['CLDR display name'], c['official_name_en'], c['UNTERM English Short']]
      .flatMap((n) => {
        const name = (n || '').trim()
        if (!name) return []
        // "United States of America (the)" is also "United States", which is
        // what the port lists call it. Both spellings are the same country.
        const plain = name.replace(/\s*\(the\)$/i, '').replace(/^the\s+/i, '').trim()
        return [name, plain, plain.replace(/\s+of America$/i, '').trim()]
      })
      .filter(Boolean))],
    // A few countries use more than one currency; the file lists them
    // comma-separated and the first is the one goods are invoiced in.
    currency: (c['ISO4217-currency_alphabetic_code'] || '').split(',')[0].trim(),
  }))
  .sort((a, b) => a.name.localeCompare(b.name))

writeFileSync(OUT, `/**
 * ISO 3166 countries with the currency each trades in.
 *
 * Generated by scripts/dataverse/generate-countries.mjs from
 * ${SOURCE}
 * — do not edit by hand; re-run the script.
 */

export interface Country {
  /** ISO 3166-1 alpha-2, which is what an airway bill carries. */
  code: string;
  code3: string;
  /** UN M49 numeric code, as used by Comtrade. */
  numeric: number;
  name: string;
  /** Other spellings the app's own data uses for it. */
  aliases: string[];
  /** ISO 4217, blank where a country has no currency of its own. */
  currency: string;
}

export const COUNTRIES: Country[] = ${JSON.stringify(countries, null, 2)};
`)
writeFileSync(OUT_MJS, `/**
 * The same country list the app carries, for the import scripts.
 *
 * Generated by scripts/dataverse/generate-countries.mjs — do not edit by hand.
 */
export const COUNTRIES = ${JSON.stringify(countries, null, 2)};
`)
console.log(`  ${countries.length} countries written`)
