/**
 * Row interfaces for every table the app reads, generated from the schema.
 *
 * The pages used to take their row shape from the demo array they were planted
 * with: empty the array and `ts.hours` becomes `unknown`, because nothing else
 * ever said what a timesheet is. Deriving it from the Dataverse schema says it
 * once, correctly, and makes a page that reads an unmapped field fail to
 * compile rather than render a blank column.
 *
 * Run: npm run dataverse:rowtypes
 */
import { readFileSync, writeFileSync } from 'node:fs'

const schema = JSON.parse(readFileSync('dataverse/farmtrack.dataverse.schema.json', 'utf8'))
const tableMap = readFileSync('src/services/tableMap.ts', 'utf8')

/** Dataverse column type -> what the app sees after the store translates it. */
const TS = {
  autonumber: 'string', string: 'string', memo: 'string',
  date: 'string', datetime: 'string',
  // Choices arrive as their label and lookups as the target's descriptive
  // name — the store translates both on the way in and out.
  choice: 'string', lookup: 'string',
  integer: 'number', decimal: 'number', currency: 'number',
  boolean: 'boolean',
}

/** logical name -> { column (lower) -> ts type } */
const columns = new Map()
for (const t of schema.tables) {
  const cols = new Map()
  for (const c of t.columns) cols.set(c.schemaName.toLowerCase(), TS[c.type] ?? 'string')
  columns.set(t.schemaName.toLowerCase(), cols)
}

/** app table key -> { dataSource, fields } straight out of tableMap.ts */
const bindings = []
for (const m of tableMap.matchAll(
  /^ {2}(\w+): \{\s*\n\s*dataSource: "(\w+)",\s*\n\s*primaryKey: "(\w+)",([\s\S]*?)\n {2}\},/gm
)) {
  const [, key, dataSource, primaryKey, body] = m
  const fields = [...body.matchAll(/(\w+): "((?:bv_|_bv_)[\w]+)"/g)]
    // A lookup is mapped as _bv_bedid_value; only that form carries the
    // wrapper. Stripping "_value" unconditionally turned bv_value into "bv".
    .map(([, app, col]) => [app, col.startsWith('_') ? col.slice(1).replace(/_value$/, '') : col])
  bindings.push({ key, dataSource, primaryKey, fields })
}

const pascal = (s) => s[0].toUpperCase() + s.slice(1)
const out = [
  '/**',
  ' * GENERATED by scripts/dataverse/generate-rowtypes.mjs — do not edit.',
  ' *',
  ' * One interface per table the app reads, built from the Dataverse schema and',
  ' * the field map in tableMap.ts. Every column is optional because Dataverse',
  ' * returns nothing for an empty cell; only `id` is always present.',
  ' *',
  ' * Regenerate with: npm run dataverse:rowtypes',
  ' */',
  '',
]

// The logical table name behind a dataSource: tableMap names entity sets, the
// schema names tables, and the two differ wherever Dataverse pluralised oddly.
const logicalOf = (dataSource, primaryKey) => {
  const fromKey = primaryKey.replace(/id$/, '')
  if (columns.has(fromKey)) return fromKey
  const trimmed = dataSource.replace(/e?s$/, '')
  return columns.has(trimmed) ? trimmed : null
}

let missing = 0
for (const b of bindings.sort((a, z) => a.key.localeCompare(z.key))) {
  const logical = logicalOf(b.dataSource, b.primaryKey)
  const cols = logical ? columns.get(logical) : null
  const name = `${pascal(b.key)}Row`
  out.push(`export interface ${name} {`, '  id: string;')
  for (const [app, col] of b.fields) {
    const t = cols?.get(col.toLowerCase())
    if (!t) missing++
    out.push(`  ${/^[a-zA-Z_$][\w$]*$/.test(app) ? app : JSON.stringify(app)}?: ${t ?? 'string'};`)
  }
  // The generic components (DataTable, FormModal) speak in Record<string,
  // unknown>. Without an index signature every page would need a cast to hand
  // them a row, which is noise that hides the casts that mean something.
  out.push('  [key: string]: unknown;', '}', '')
}

writeFileSync('src/services/rowTypes.generated.ts', out.join('\n'))

/**
 * What kind of column each one is, per data source.
 *
 * An empty form field arrives as "". Dataverse accepts that for text and
 * rejects it outright for a date, a number or a choice — with a 400 that fails
 * the whole record, not just the field. Knowing the kind is what lets the
 * store drop the blank instead of sending it.
 */
const kinds = ['/**',
  ' * GENERATED by scripts/dataverse/generate-rowtypes.mjs — do not edit.',
  ' *',
  ' * Dataverse column -> what it holds, per data source. Used to decide what an',
  ' * empty form field means: nothing at all for a date, number, choice or',
  ' * boolean, and a cleared value for text.',
  ' *',
  ' * Regenerate with: npm run dataverse:rowtypes',
  ' */',
  '',
  'export type ColumnKind = "text" | "number" | "date" | "boolean" | "choice" | "lookup";',
  '',
  'export const COLUMN_KIND: Record<string, Record<string, ColumnKind>> = {']

const KIND = {
  autonumber: 'text', string: 'text', memo: 'text',
  date: 'date', datetime: 'date',
  choice: 'choice', lookup: 'lookup',
  integer: 'number', decimal: 'number', currency: 'number',
  boolean: 'boolean',
}

for (const b of bindings) {
  const logical = logicalOf(b.dataSource, b.primaryKey)
  const table = logical ? schema.tables.find((t) => t.schemaName.toLowerCase() === logical) : null
  if (!table) continue
  kinds.push(`  ${JSON.stringify(b.dataSource)}: {`)
  for (const c of table.columns) {
    kinds.push(`    ${JSON.stringify(c.schemaName.toLowerCase())}: ${JSON.stringify(KIND[c.type] ?? 'text')},`)
  }
  kinds.push('  },')
}
kinds.push('};', '')
writeFileSync('src/services/columnKinds.generated.ts', kinds.join('\n'))
console.log(`  ${bindings.length} interfaces written${missing ? `, ${missing} columns not found in the schema (typed as string)` : ''}`)
